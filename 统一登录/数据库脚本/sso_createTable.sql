drop TABLE
    SSO_PLATFORM;
CREATE TABLE
    SSO_PLATFORM
    (
        ID VARCHAR2(36) NOT NULL,
        PLATFORM_NAME VARCHAR2(60) NOT NULL,
        PLATFORM_URL VARCHAR2(100) NOT NULL,
        WEIGHT NUMBER DEFAULT 1 NOT NULL,
        MDTIME VARCHAR2(19),
        MDUSER VARCHAR2(50),
        REMARK1 VARCHAR2(50) DEFAULT '',
        REMARK2 VARCHAR2(50) DEFAULT '',
        STATUS NUMBER DEFAULT 0,
        ICON VARCHAR2(100),
        COOKIE_KEY VARCHAR2(100) DEFAULT 'username',
        DESCRIBE VARCHAR2(1000),
        PLATFORM_CODE VARCHAR2(100) NOT NULL,
        CONSTRAINT PK_SYS_PLATFORM PRIMARY KEY (ID)
    );
COMMENT ON TABLE SSO_PLATFORM
IS
    '平台管理信息';
COMMENT ON COLUMN SSO_PLATFORM.ID
IS
    'ID';
COMMENT ON COLUMN SSO_PLATFORM.PLATFORM_NAME
IS
    '平台名称';
COMMENT ON COLUMN SSO_PLATFORM.PLATFORM_URL
IS
    '平台地址';
COMMENT ON COLUMN SSO_PLATFORM.WEIGHT
IS
    '权重';
COMMENT ON COLUMN SSO_PLATFORM.MDTIME
IS
    '创建时间(yyyy-MM-dd HH:mm:ss)';
COMMENT ON COLUMN SSO_PLATFORM.MDUSER
IS
    '更新人';
COMMENT ON COLUMN SSO_PLATFORM.REMARK1
IS
    '备注2';
COMMENT ON COLUMN SSO_PLATFORM.REMARK2
IS
    '备注3';
COMMENT ON COLUMN SSO_PLATFORM.STATUS
IS
    '可用状态(0:不可用,1:可用)';
COMMENT ON COLUMN SSO_PLATFORM.ICON
IS
    '图标名';
COMMENT ON COLUMN SSO_PLATFORM.COOKIE_KEY
IS
    '身份标识';
COMMENT ON COLUMN SSO_PLATFORM.DESCRIBE
IS
    '描述';
COMMENT ON COLUMN SSO_PLATFORM.PLATFORM_CODE
IS
    '平台编码';
	
