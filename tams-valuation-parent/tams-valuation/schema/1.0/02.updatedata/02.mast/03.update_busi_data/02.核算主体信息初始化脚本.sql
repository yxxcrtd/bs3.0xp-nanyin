/**核算分层信息初始化脚本 add by wujie start**/
delete BOK_ACCT_LAYERING_INFO;
INSERT INTO BOK_ACCT_LAYERING_INFO(BOOKSET_ID,LAYERING_ID,LAYERING_NAME,F_LAYERING_ID,BOK_DETAIL_ID,BUSI_ID,
BUSI_DETAIL_TYPE,VDATE,MDATE,CALENDAR_ID,BRANCH,LEV,CUR_LEV,S_BRANCH
,CREATE_USER,CREATE_DEPT,CREATE_TIME,UPDATE_USER,UPDATE_TIME) 
SELECT A.BOOKSET_ID ,A.ACCT_SUBJECT_ID AS LAYERING_ID,A.BOOKSET_NAME AS LAYERING_NAME,
NULL AS F_LAYERING_ID,C.BOK_DETAIL_ID,
A.ACCT_SUBJECT_ID AS BUSI_ID,
A.ACCT_SUBJECT_TYPE AS BUSI_DETAIL_TYPE,
B.VDATE,B.ACTMDATE AS MDATE,B.CALENDAR_ID,'0' AS BRANCH,
'1' AS LEV,1 AS CUR_LEV,0 AS S_BRANCH,
'interf' as create_user,null as create_dept,
sysdate as create_time,'interf' as update_user,
sysdate as update_time
FROM BOK_BOOKSET A
LEFT JOIN FIN_PRODUCT B ON A.ACCT_SUBJECT_ID = B.FINPROD_ID 
LEFT JOIN BOK_DETAIL_ID C ON A.ACCT_SUBJECT_ID = C.BUSI_ID AND A.BOOKSET_ID = C.BOOKSET_ID
WHERE B.FINPROD_TYPE IN ('F18','F16') AND C.BUSI_DETAIL_TYPE IN ('F18','F16')
AND A.BOOKSET_ID NOT IN ('00000000000000000002','00000000000000000003','00000000000000000004','00000000000000000001');
