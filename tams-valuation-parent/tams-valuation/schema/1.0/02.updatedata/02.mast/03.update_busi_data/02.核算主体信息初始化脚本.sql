UPDATE BOK_BOOKSET 
  SET ACCT_SUBJECT_TYPE = DECODE(ACCT_SUBJECT_TYPE,'01','F16','02','F18',ACCT_SUBJECT_TYPE)
WHERE BOOKSET_ID NOT IN ('00000000000000000001','00000000000000000002','00000000000000000003','00000000000000000004');

DELETE FROM BOK_ACCT_SUBJECT_INFO A
WHERE EXISTS (
      SELECT * FROM BOK_BOOKSET B WHERE A.ACCT_SUBJECT_ID = B.ACCT_SUBJECT_ID AND A.ACCT_SUBJECT_TYPE = B.ACCT_SUBJECT_TYPE
);

INSERT INTO BOK_ACCT_SUBJECT_INFO 
SELECT 
 T.ACCT_SUBJECT_ID,
 T.ACCT_SUBJECT_TYPE,
 T.BOOKSET_NAME,
 'interf',
 null,
 sysdate,
 'interf',
 sysdate
FROM BOK_BOOKSET T
WHERE T.BOOKSET_ID NOT IN ('00000000000000000002','00000000000000000003','00000000000000000004','00000000000000000001');

