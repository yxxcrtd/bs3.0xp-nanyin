package com.joyintech.tams.report.home.dto;

public class HomeCellDto {
	private String cellClass;
	
	private String cellText;

	private String cellPageid;
	
	private String layId;
	
	private String dataType;
	
	private String dataSubtype;
	
	private String dataNum;
	
	private String dataRepCode;

	
	public String getCellClass() {
		return cellClass;
	}

	public void setCellClass(String cellClass) {
		this.cellClass = cellClass;
	}

	public String getCellText() {
		return cellText;
	}

	public void setCellText(String cellText) {
		this.cellText = cellText;
	}

	public String getCellPageid() {
		return cellPageid;
	}

	public void setCellPageid(String cellPageid) {
		this.cellPageid = cellPageid;
	}

	public String getLayId() {
		return layId;
	}

	public void setLayId(String layId) {
		this.layId = layId;
	}

	public String getDataType() {
		return dataType;
	}

	public void setDataType(String dataType) {
		this.dataType = dataType;
	}

	public String getDataSubtype() {
		return dataSubtype;
	}

	public void setDataSubtype(String dataSubtype) {
		this.dataSubtype = dataSubtype;
	}

	public String getDataNum() {
		return dataNum;
	}

	public void setDataNum(String dataNum) {
		this.dataNum = dataNum;
	}

	public String getDataRepCode() {
		return dataRepCode;
	}

	public void setDataRepCode(String dataRepCode) {
		this.dataRepCode = dataRepCode;
	}
	
}
