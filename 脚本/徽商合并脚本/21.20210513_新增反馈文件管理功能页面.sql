/*中债反馈文件信息表*/
DROP TABLE CHB_FEEDBACK_FILE;
CREATE TABLE CHB_FEEDBACK_FILE (
    RTN_REP_MES_NO VARCHAR2(32) NOT NULL,
	SEND_REP_MES_NO VARCHAR2(32),
	REPORT_SEND_DATE DATE,
	REPORT_ACCEPT_DATE DATE,
	BUSINESS_GROUP_TYPE VARCHAR2(10),
	REPORT_ETR_TYPE VARCHAR2(10),
	FILE_ID VARCHAR2(50),
	FILE_NAME VARCHAR2(256),
	FILE_PATH VARCHAR2(200),
	HANDLE_STATUS VARCHAR2(10),
	MOVE_FLAG VARCHAR2(10),
	MOVE_PATH VARCHAR2(200),
	FEEDBACK_MSG CLOB,
    CREATE_USER VARCHAR2(20 BYTE) NOT NULL ENABLE,
    CREATE_DEPT VARCHAR2(32 BYTE),
    CREATE_TIME TIMESTAMP (6) NOT NULL ENABLE,
    UPDATE_USER VARCHAR2(20 BYTE) NOT NULL ENABLE,
    UPDATE_TIME TIMESTAMP (6) NOT NULL ENABLE,
    CONSTRAINT PK_CHB_FEEDBACK_FILE PRIMARY KEY (RTN_REP_MES_NO)
);

COMMENT ON COLUMN CHB_FEEDBACK_FILE.RTN_REP_MES_NO IS '反馈-报文编码';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.SEND_REP_MES_NO IS '发送-报文编码';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.REPORT_SEND_DATE IS '报文发送时间';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.REPORT_ACCEPT_DATE IS '报文接收时间';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.BUSINESS_GROUP_TYPE IS '业务组类型';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.REPORT_ETR_TYPE IS '报文指令类型';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.FILE_ID IS '文件ID';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.FILE_NAME IS '文件名称';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.FILE_PATH IS '文件路径';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.HANDLE_STATUS IS '处理状态';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.MOVE_FLAG IS '是否迁移';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.MOVE_PATH IS '迁移目录';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.FEEDBACK_MSG IS '反馈消息';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.CREATE_USER IS '创建人';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.CREATE_DEPT IS '创建部门';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.UPDATE_USER IS '更新人';
COMMENT ON COLUMN CHB_FEEDBACK_FILE.UPDATE_TIME IS '更新时间';
COMMENT ON TABLE CHB_FEEDBACK_FILE  IS '中债反馈文件信息表';



