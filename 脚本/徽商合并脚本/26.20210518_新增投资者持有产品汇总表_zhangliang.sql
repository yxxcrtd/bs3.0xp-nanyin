DROP TABLE CHB_INVESTHOLD_INFO_SUB_SUM;

CREATE TABLE CHB_INVESTHOLD_INFO_SUB_SUM
(
	 PRODID VARCHAR2(36 BYTE),
	 PRD_REGIST_CODE VARCHAR2(20 BYTE),
	 HOLD_DATE DATE,
	 CCY VARCHAR2(3 BYTE),
	 AMOUNT DECIMAL(15,2),
	 QTY DECIMAL(18,5),
	 CNY_AMT DECIMAL(15,2),
	 SINGLE_TOTAL DECIMAL(10),
	 LEGAL_TOTAL DECIMAL(10),
	 UNLEGAL_TOTAL DECIMAL(10),
	 REMARK VARCHAR2(1000 BYTE),
	 CREATE_USER VARCHAR2(20 BYTE) NOT NULL,
	 CREATE_TIME TIMESTAMP (6) NOT NULL,
	 UPDATE_USER VARCHAR2(20 BYTE) NOT NULL,
	 UPDATE_TIME TIMESTAMP (6) NOT NULL
);

COMMENT ON TABLE CHB_INVESTHOLD_INFO_SUB_SUM IS '投资者持有产品汇总表';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.PRODID IS '产品代码';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.PRD_REGIST_CODE IS '产品登记编码';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.HOLD_DATE IS '持有日期';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.CCY IS '币种';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.AMOUNT IS '持有金额';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.QTY IS '持有份额';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.CNY_AMT IS '折算成人民币金额(元)';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.SINGLE_TOTAL IS '个人投资者总数';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.LEGAL_TOTAL IS '法人投资者总数';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.UNLEGAL_TOTAL IS '非法人投资者总数';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.REMARK IS '备注';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.CREATE_USER IS '创建人';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.UPDATE_USER IS '更新人';
COMMENT ON COLUMN CHB_INVESTHOLD_INFO_SUB_SUM.UPDATE_TIME IS '更新时间';