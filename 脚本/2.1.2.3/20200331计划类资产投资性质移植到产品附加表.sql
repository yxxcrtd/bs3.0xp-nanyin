--将资产投资性质移植到FIN_PRODUCT_ADD表里
  update FIN_PRODUCT_ADD
    SET INVEST_NATURE = (
    SELECT INVESTMENT_ATTRIBUTES
    FROM PA_FIN_PRODUCT 
    where FIN_PRODUCT_ADD.FINPROD_ID = PA_FIN_PRODUCT.FINPROD_ID
   ) where FINPROD_ID IN (
     SELECT FINPROD_ID FROM FIN_PRODUCT 
     WHERE FIN_PRODUCT_ADD.FINPROD_ID = FIN_PRODUCT.FINPROD_ID
     AND FIN_PRODUCT.FINPROD_TYPE2 ='F17'
     AND FIN_PRODUCT.PROFIT_TYPE IN('01','03')
   );
 
    UPDATE FIN_PRODUCT_ADD
	   SET INVEST_NATURE = (
	     SELECT padd.INVEST_NATURE 
	      FROM FIN_PRODUCT
        INNER JOIN FIN_PRODUCT_ADD padd
              ON FIN_PRODUCT.P_FINPROD_ID = padd.FINPROD_ID
            WHERE FIN_PRODUCT_ADD.FINPROD_ID=FIN_PRODUCT.FINPROD_ID 
	   ) 
   WHERE FINPROD_ID IN (
     SELECT FINPROD_ID FROM FIN_PRODUCT 
     WHERE FIN_PRODUCT_ADD.FINPROD_ID = FIN_PRODUCT.FINPROD_ID
     AND FIN_PRODUCT.FINPROD_TYPE2 ='F17'  
	 AND FIN_PRODUCT.PROFIT_TYPE = '02'
	 AND FIN_PRODUCT.P_FINPROD_ID IS NOT NULL
     );