COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIGDETAIL.CREATE_DEPT IS '创建部门';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIGDETAIL.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIGDETAIL.UPDATE_USER IS '更新人';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIGDETAIL.UPDATE_TIME IS '更新时间';
