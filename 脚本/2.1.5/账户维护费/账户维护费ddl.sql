/*账户维护费设置表*/
DROP TABLE TRD_ACCOUNTMF_CONFIG;
CREATE TABLE TRD_ACCOUNTMF_CONFIG (	
    SEQ_NO VARCHAR2(32 BYTE) NOT NULL ENABLE, 
    FEE_TYPE VARCHAR2(50 BYTE), 
    SEC_ACCT_ID VARCHAR2(50 BYTE),
    REGIST_ORG VARCHAR2(50 BYTE), 
    PAY_CYCLE VARCHAR2(50 BYTE), 
    PAY_DATE VARCHAR2(50 BYTE),
    POSITION_START_DATE DATE,
    POSITION_END_DATE DATE,
    ACT_POSITION_END_DATE DATE,
    FEE_AMT_TOTAL NUMBER(30,2),
    DEAL_STATUS VARCHAR2(50 BYTE),
    CREATE_USER VARCHAR2(20 BYTE) NOT NULL ENABLE, 
    CREATE_DEPT VARCHAR2(32 BYTE), 
    CREATE_TIME TIMESTAMP (6) NOT NULL ENABLE, 
    UPDATE_USER VARCHAR2(20 BYTE) NOT NULL ENABLE, 
    UPDATE_TIME TIMESTAMP (6) NOT NULL ENABLE,
    CONSTRAINT PK_TRD_ACCOUNTMF_CONFIG PRIMARY KEY (SEQ_NO)
);

COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.SEQ_NO IS '流水号';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.FEE_TYPE IS '费用品种';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.SEC_ACCT_ID IS '证券账户';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.REGIST_ORG IS '登记托管机构';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.PAY_CYCLE IS '支付频率';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.PAY_DATE IS '支付日（几号）';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.POSITION_START_DATE IS '计提开始日';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.POSITION_END_DATE IS '计提结束日';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.ACT_POSITION_END_DATE IS '实际计提结束日';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.FEE_AMT_TOTAL IS '每季费用金额';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.DEAL_STATUS IS '交易状态';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.CREATE_USER IS '创建人';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.CREATE_DEPT IS '创建部门';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.UPDATE_USER IS '更新人';
COMMENT ON COLUMN TRD_ACCOUNTMF_CONFIG.UPDATE_TIME IS '更新时间';
COMMENT ON TABLE TRD_ACCOUNTMF_CONFIG  IS '账户维护费设置表';



