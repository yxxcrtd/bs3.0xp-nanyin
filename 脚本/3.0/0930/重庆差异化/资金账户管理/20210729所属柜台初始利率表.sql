--所属柜台初始利率表
DROP TABLE FIN_INITRATE_DATADICT;

CREATE TABLE "FIN_INITRATE_DATADICT"(
    "OWN_DEPT"    VARCHAR2(100) NOT NULL,
    "RATE"        NUMBER(30,14) NOT NULL,
    "CREATE_USER" VARCHAR2(20) NOT NULL,
    "CREATE_DEPT" VARCHAR2(32),
    "CREATE_TIME" TIMESTAMP(6) NOT NULL,
    "REMARK"      VARCHAR2(500),
    CONSTRAINT "FIN_RATE_DATADICT_PK" PRIMARY KEY ("OWN_DEPT"));


COMMENT ON COLUMN "FIN_INITRATE_DATADICT"."OWN_DEPT" IS '所属营业部';
COMMENT ON COLUMN "FIN_INITRATE_DATADICT"."RATE" IS '初始利率';
COMMENT ON COLUMN "FIN_INITRATE_DATADICT"."CREATE_USER" IS '创建人';
COMMENT ON COLUMN "FIN_INITRATE_DATADICT"."CREATE_DEPT" IS '创建部门';
COMMENT ON COLUMN "FIN_INITRATE_DATADICT"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "FIN_INITRATE_DATADICT"."REMARK" IS '备注';
