----1.资产TYPE_18字段刷为对应证券品种
--债券类资产对应证券品种为：01 债券
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '01' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE='F01');

--基金类资产对应证券品种为：02 基金
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '02' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE='F06');

--利率互换对应证券品种为：04 利率互换
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '04' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F14');

--外汇资产对应证券品种为：05 外汇
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '05' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE IN ('F11','F12','F13'));

--股票类资产对应证券品种为：06 股票
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '06' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F10');

--存款类资产和同业借款对应证券品种为：07 存款
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '07' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE IN ('F07','F21'));

--拆借类资产对应证券品种为：08 拆借
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '08' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE IN ('F08','F09'));

--回购类资产对应证券品种为：09 回购
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '09' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE IN ('F02','F03','F04','F05'));

--计划类资产
--计划类净值型资产对应证券品种为：10 计划类（净值型）
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '10' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F17' AND A.PROFIT_TYPE='01');

--计划类货币型资产对应证券品种为：11 计划类（货币型）
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '11' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F17' AND A.PROFIT_TYPE='03');

--计划类利率型资产（去除 非标债权、结构化证券、股票质押式回购、信贷资产流转项目、券商收益凭证）对应证券品种为：12 计划类（利率型）
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '12' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F17' AND A.PROFIT_TYPE='02' AND T.TYPE_1 NOT IN ('01','02','04','05','06'));

--非标债权、结构化证券、股票质押式回购、信贷资产流转项目、券商收益凭证 对应证券品种为：13 其他债权
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '13' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F17' AND T.TYPE_1 IN ('01','02','04','05','06'));

--债券借贷融入、融出 对应证券品种为：14 债券借贷
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '14' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE IN ('F23','F24'));

--期权类资产 对应证券品种为：15 期权
UPDATE FIN_PRODUCT_TYPE T SET T.TYPE_18 = '15' WHERE EXISTS ( SELECT 1 FROM FIN_PRODUCT A WHERE A.FINPROD_ID= T.FINPROD_ID AND A.FINPROD_TYPE = 'F35');


