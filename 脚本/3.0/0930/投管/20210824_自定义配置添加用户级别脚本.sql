
--自定义配置用户明细表
DROP TABLE DYN_CONFIG_INFO_USER;
CREATE TABLE "DYN_CONFIG_INFO_USER" (
    "DYN_ID" varchar2(100) NOT NULL,
    "USER_NAME" varchar2(100) NOT NULL,
    "DYN_INFO" varchar2(4000) NOT null,
    "REMARK"	VARCHAR2(100),
    "CREATE_USER" varchar2(20) NOT NULL,
    "CREATE_TIME" date NOT NULL,
    "UPDATE_USER" varchar2(20) NOT NULL ,
    "UPDATE_TIME" date NOT NULL ,
    CONSTRAINT "DYN_CONFIG_INFO_USER" PRIMARY KEY ("DYN_ID", "USER_NAME")
) ;
COMMENT ON TABLE "DYN_CONFIG_INFO_USER"  IS '动态配置信息用户明细表';
COMMENT ON COLUMN "DYN_CONFIG_INFO_USER"."DYN_ID" IS '配置主键信息';
COMMENT ON COLUMN "DYN_CONFIG_INFO_USER"."DYN_INFO" IS '配置信息';
COMMENT ON COLUMN "DYN_CONFIG_INFO_USER"."REMARK" IS '备注';