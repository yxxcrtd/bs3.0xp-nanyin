--估值表导入日期记录表
DROP TABLE VALTBL_IMPORT_DATE_TRACE;
CREATE TABLE VALTBL_IMPORT_DATE_TRACE
(
	UUID VARCHAR2(100),
	PORTFOLIO_ID VARCHAR2(50),
	VALDATE DATE,
	IMPDATE DATE NOT NULL,
	CREATE_USER VARCHAR2(20) NOT NULL,
	CREATE_DEPT VARCHAR2(32),
	CREATE_TIME TIMESTAMP(6) NOT NULL,
	UPDATE_USER VARCHAR2(20) NOT NULL,
	UPDATE_TIME TIMESTAMP(6) NOT NULL,
  CONSTRAINT VALTBL_IMPORT_DATE_TRACE PRIMARY KEY(UUID)
);
COMMENT ON TABLE VALTBL_IMPORT_DATE_TRACE IS '估值表导入日期记录表';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.UUID IS '主键';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.PORTFOLIO_ID IS '委外组合代码';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.VALDATE IS '估值日期';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.IMPDATE IS '平台日';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.CREATE_USER IS '创建人';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.UPDATE_TIME IS '修改时间';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.CREATE_DEPT IS '创建部门';
COMMENT ON COLUMN VALTBL_IMPORT_DATE_TRACE.UPDATE_USER IS '修改人';