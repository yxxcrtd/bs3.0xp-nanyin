and B.TRADE_MARKET in (''03'',''04'')
and D.TYPE_6 not in (''B17'',''B14'',''B15'')
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''';
