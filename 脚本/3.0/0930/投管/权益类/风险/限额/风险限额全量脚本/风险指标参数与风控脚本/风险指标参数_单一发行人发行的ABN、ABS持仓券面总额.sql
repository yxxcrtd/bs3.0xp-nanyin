    SELECT FCP.FINPROD_ID, (100 - SUM(NVL(FCP.PRIN_AMT,0))) AS FACEVALUE
    FROM FIN_CASH_PLAN FCP
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = FCP.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    WHERE FCP.MDATE <= DATE''${valDate}'' AND FCP.FINPROD_TYPE2 = ''F01''
    AND FPT.TYPE_6 = ''B13''
    GROUP BY FCP.FINPROD_ID
)
SELECT SUM(NVL(AMT.SHARE_AMT,0) * NVL(FACE.FACEVALUE,100)) RVALUE, AMT.ISSUER RKEY, AMT.CUSTOMER_NAME RKEYCN FROM (
    SELECT SUM(NVL(PSP.SHARE_AMT,0)) SHARE_AMT, FP.FINPROD_ID, FP.ISSUER, MCI.CUSTOMER_NAME
    FROM PTL_SEC_PIERCE_VALUTION PSP
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = PSP.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN MST_CUSTOMER_INFO MCI ON MCI.CUSTOMER_ID = FP.ISSUER
    WHERE PSP.CDATE = DATE ''${valDate}'' - 1 AND FPT.TYPE_6 = ''B13''
    GROUP BY FP.FINPROD_ID,FP.ISSUER, MCI.CUSTOMER_NAME
  UNION ALL
    SELECT
        nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.SHARE_AMT*-1, n.SHARE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T04'', decode(TRADE_STATUS, ''03'', n.SHARE_AMT*-1, n.SHARE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T52'', decode(TRADE_STATUS, ''03'', n.SHARE_AMT*-1, n.SHARE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.SHARE_AMT*-1, n.SHARE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T03'', decode(TRADE_STATUS, ''03'', n.SHARE_AMT*-1, n.SHARE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T19'', decode(TRADE_STATUS, ''03'', n.SHARE_AMT*-1, n.SHARE_AMT))), 0)
