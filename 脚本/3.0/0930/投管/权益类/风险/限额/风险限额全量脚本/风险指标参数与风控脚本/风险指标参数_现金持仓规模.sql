union all  
select t.PTL_BAG_ID as RKEY,  
( select nvl(sum(nvl(pspv.MARKET_VALUE,0)+nvl(pspv.TDY_INTINCEXP,0)),0) as  TRADE_AMT from PTL_CASH_POSITION n
