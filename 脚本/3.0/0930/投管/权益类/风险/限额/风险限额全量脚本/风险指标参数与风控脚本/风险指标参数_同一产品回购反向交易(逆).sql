                FROM TRD_PRODUCT_TEMP_DEAL A
                INNER JOIN TRD_PRODUCT_TEMP_DEAL_ADD B
                ON A.TRADE_ID = B.TRADE_ID
                INNER JOIN FIN_TRADE_PRODUCT C
                ON A.FINPROD_ID = C.FINPROD_ID
                WHERE A.FINPROD_TYPE2 IN (''F03'')
                AND A.PS IN(''04'',''T01'')
