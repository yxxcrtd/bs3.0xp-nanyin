V_CONTENT_04 CLOB := 'WITH PLANNET AS (
    -- 计划类资产净值
    SELECT FPV.FINPROD_ID,FPV.VALUATION  FROM FIN_PRODUCT_VALUATION FPV
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FPV.FINPROD_ID
    LEFT JOIN (
        SELECT FINPROD_ID, MAX(VAL_DATE) VAL_DATE FROM FIN_PRODUCT_VALUATION
        WHERE VAL_DATE <= DATE ''${valDate}'' - 1
        GROUP BY FINPROD_ID
    ) FPVMAX ON FPVMAX.FINPROD_ID = FPV.FINPROD_ID AND FPVMAX.VAL_DATE = FPV.VAL_DATE
    WHERE FPV.FINPROD_TYPE2 = ''F17'' AND FPT.TYPE_10 = ''N001''
)
SELECT SUM(TRADE_AMT) RVALUE,MANAGER RKEY,CUSTOMER_NAME RKEYCN FROM (
    SELECT SUM(NVL(PLANNET.VALUATION,1) * NVL(PSV.SHARE_AMT ,0)) TRADE_AMT,FP.MANAGER,MCI.CUSTOMER_NAME
    FROM PTL_SEC_PIERCE_VALUTION PSV
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = PSV.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN MST_CUSTOMER_INFO MCI ON MCI.CUSTOMER_ID = FP.MANAGER
    LEFT JOIN PLANNET ON PLANNET.FINPROD_ID = PSV.FINPROD_ID
    WHERE FP.FINPROD_TYPE2 = ''F17'' AND PSV.CDATE = DATE ''${valDate}'' - 1 AND FPT.TYPE_10 = ''N001''
    GROUP BY FP.MANAGER,MCI.CUSTOMER_NAME
  UNION ALL
    SELECT
        nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T04'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T52'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T03'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T19'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T07'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T08'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T09'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T11'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T22'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T23'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T39'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0) AS TRADE_AMT,
        FP.MANAGER,MCI.CUSTOMER_NAME
    FROM TRD_PRODUCT_DEAL_ADD m
    INNER JOIN TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
  INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN MST_CUSTOMER_INFO MCI ON MCI.CUSTOMER_ID = FP.MANAGER
    WHERE n.TRADE_DATE = DATE''${valDate}'' AND FP.FINPROD_TYPE2 = ''F17'' AND FPT.TYPE_10 = ''N001''
    AND n.PS IN (''T01'', ''T02'', ''T03'', ''T04'', ''T19'', ''T07'', ''T08'', ''T09'', ''T11'', ''T52'', ''T22'', ''T23'', ''T39'')
    GROUP BY FP.MANAGER,MCI.CUSTOMER_NAME
  UNION ALL
    SELECT
        nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T04'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T52'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T19'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T03'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)  AS TRADE_AMT,
        FP.MANAGER,MCI.CUSTOMER_NAME
    FROM WFL_TRD_PRODUCT_DEAL_ADD m
    INNER JOIN WFL_TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID
  INNER JOIN SYS_WFL_BUSINESS_LIST swbl on n.WORKFLOW_ID = swbl.SEQ_NO and swbl.PROCESS_STATE != ''BACK''
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
  INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN MST_CUSTOMER_INFO MCI ON MCI.CUSTOMER_ID = FP.MANAGER
    WHERE n.TRADE_DATE = DATE''${valDate}'' AND FP.FINPROD_TYPE2 = ''F17'' AND FPT.TYPE_10 = ''N001''
    AND n.PS IN (''T01'', ''T02'', ''T03'', ''T04'', ''T19'', ''T52'')
    GROUP BY FP.MANAGER,MCI.CUSTOMER_NAME
