   ELSE  NVL(-1*n.SHARE_AMT,0)
     END)  AS SHARE_AMT,
     ASSET.FINPROD_ID RKEY, ASSET.MDATE, FP.FINPROD_NAME
    FROM TRD_PRODUCT_TEMP_DEAL_ADD m
    INNER JOIN TRD_PRODUCT_TEMP_DEAL n ON m.TRADE_ID = n.TRADE_ID
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
    INNER JOIN ASSET ON ASSET.FINPROD_ID = n.FINPROD_ID
    WHERE n.TRADE_DATE = DATE''${valDate}'' AND m.PORTFOLIO_ID IN ${portfolioCode}
    AND n.TRADE_STATUS = ''01''
    AND n.IS_CANCEL = ''N''
    AND n.PS IN (''T01'', ''T02'', ''T03'', ''T05'',''T06'', ''T07'',''T12'',''T19'', ''T18'', ''T23'', ''T38'', ''T39'',''T49'',''T64'',''T62'')
    GROUP BY ASSET.FINPROD_ID, ASSET.MDATE, FP.FINPROD_NAME
  UNION ALL
    SELECT
     SUM(CASE  WHEN n.PS IN(''T01'',''T05'',''T18'',''T64'',''T12'') THEN NVL(n.SHARE_AMT,0)
    WHEN n.PS =''T49'' THEN NVL(-1*n.SHARE_AMT,0)
   ELSE  NVL(-1*n.SHARE_AMT,0)
     END)  AS SHARE_AMT,
     ASSET.FINPROD_ID RKEY, ASSET.MDATE, FP.FINPROD_NAME
    FROM WFL_TRD_PRODUCT_DEAL_ADD m
    INNER JOIN WFL_TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID AND n.TRADE_STATUS != ''03''
    INNER JOIN SYS_WFL_BUSINESS_LIST swbl on n.WORKFLOW_ID = swbl.SEQ_NO and swbl.PROCESS_STATE != ''BACK''
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
    INNER JOIN ASSET ON ASSET.FINPROD_ID = n.FINPROD_ID
