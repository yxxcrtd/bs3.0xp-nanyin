V_CONTENT_01_02_03 CLOB := 'SELECT 0 RVALUE,B.FINPROD_ID RKEY FROM FIN_PRODUCT B
inner join FIN_PRODUCT_TYPE D
on B.FINPROD_ID = D.FINPROD_ID
where B.FINPROD_TYPE2 IN(''F01'',''F32'')
and B.TRADE_MARKET =''01''
