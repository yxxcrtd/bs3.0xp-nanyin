and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''
union all
--3.流程交易表
select A.FINPROD_ID||'',''||A.TRADE_ID AS RKEY, A.UNIT_CPRICE AS RVALUE
from WFL_TRD_PRODUCT_DEAL  A
inner join WFL_TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS =''01''
and substr(A.TRADE_ID,length(A.TRADE_ID),length(A.TRADE_ID)-1)!=''R''
inner join FIN_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
inner join FIN_PRODUCT_TYPE D
on A.FINPROD_ID = D.FINPROD_ID
where A.FINPROD_TYPE2 IN(''F01'',''F32'')
AND A.PS IN (''T01'',''T02'',''T03'')
and B.TRADE_MARKET =''01''
and D.TYPE_6!=''B17''
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''
union all
--4.内部卖出流程中交易表
select A.FINPROD_ID||'',''||A.TRADE_ID AS RKEY, A.YIELD AS RVALUE
from WFL_TRD_PRODUCT_DEAL  A
inner join WFL_TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS =''01''
and substr(A.TRADE_ID,length(A.TRADE_ID),length(A.TRADE_ID)-1)!=''R''
inner join FIN_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
inner join FIN_PRODUCT_TYPE D
on A.FINPROD_ID = D.FINPROD_ID
where A.FINPROD_TYPE2 IN(''F01'',''F32'')
AND A.PS =''T02''
and B.TRADE_MARKET  =''01''
and D.TYPE_6!=''B17''
and A.counter_id IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''
AND EXISTS (SELECT 1 FROM SYS_PARA WHERE PARA_CODE = ''is_auto_generate_negate_deal'' AND PARAM_VALUE = ''Y'')';

----事后(日终)
V_CONTENT_05 CLOB := 'select A.FINPROD_ID||'',''||A.TRADE_ID AS RKEY, A.UNIT_CPRICE AS RVALUE
from TRD_PRODUCT_DEAL  A
inner join TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS =''01''
and NVL(A.IS_CANCEL,''N'') =''N''
inner join FIN_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
inner join FIN_PRODUCT_TYPE D
on A.FINPROD_ID = D.FINPROD_ID
where A.FINPROD_TYPE2 IN(''F01'',''F32'')
AND A.PS IN (''T01'',''T02'',''T03'')
and B.TRADE_MARKET =''01''
and D.TYPE_6!=''B17''
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''';
