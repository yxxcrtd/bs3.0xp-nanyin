V_CONTENT_01_02_03 CLOB := 'WITH FACE AS (
    -- 资产支持债券可用面值
    SELECT FCP.FINPROD_ID, (100 - SUM(NVL(FCP.PRIN_AMT,0))) AS FACEVALUE
    FROM FIN_CASH_PLAN FCP
    INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = FCP.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    WHERE FCP.MDATE <= DATE''${valDate}'' AND FCP.FINPROD_TYPE2 = ''F01''
    AND FPT.TYPE_6 = ''B13''
    GROUP BY FCP.FINPROD_ID
)
SELECT SUM(NVL(PSP.AMOUNT,0) * NVL(F.FACEVALUE,100)) RVALUE, PSP.FINPROD_ID RKEY FROM PTL_SEC_POSITION PSP
INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = PSP.FINPROD_ID
INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
LEFT JOIN FACE F ON F.FINPROD_ID = PSP.FINPROD_ID
