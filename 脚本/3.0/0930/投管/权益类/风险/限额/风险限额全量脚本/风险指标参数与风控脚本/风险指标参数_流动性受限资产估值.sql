                -- 存款类资产
                SELECT FPT.FINPROD_ID,FPT.MDATE,NVL(FPT.CALENDAR_ID,''01'') CALENDAR_ID FROM FIN_PRODUCT FPT
                LEFT JOIN FIN_PRODUCT_TYPE T1 ON FPT.FINPROD_ID = T1.FINPROD_ID 
