    WHERE M.PORTFOLIO_ID IN  ${portfolioCode} AND N.TRADE_DATE = DATE''${valDate}'' AND RT.GRADE_RESULT = ''02''
    AND  n.PS IN (''T01'', ''T02'', ''T03'', ''T04'', ''T19'',''T49'', ''T52'', ''T64'',''T63'')
    AND n.TRADE_STATUS = ''01''
    AND n.IS_CANCEL = ''N''
  GROUP BY T2.ISSUER
  UNION ALL
    SELECT
    SUM(nvl( n.TRADE_AMT, 0))   AS TRADE_AMT, T2.ISSUER RKEY
    FROM WFL_TRD_PRODUCT_DEAL_ADD M
