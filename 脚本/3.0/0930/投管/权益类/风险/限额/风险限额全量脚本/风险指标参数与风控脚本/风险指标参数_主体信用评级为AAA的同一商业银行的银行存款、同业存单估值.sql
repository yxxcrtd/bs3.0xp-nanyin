V_CONTENT_04 CLOB := 'SELECT SUM(NVL(TRADE_AMT,0)) AS RVALUE, RKEY FROM (
    SELECT
        SUM(NVL(VAL.MARKET_VALUE ,0)) TRADE_AMT, PRD.ISSUER RKEY
    FROM PTL_SEC_PIERCE_VALUTION VAL
    INNER JOIN FIN_PRODUCT PRD ON VAL.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE TYP ON TYP.FINPROD_ID = VAL.FINPROD_ID AND (TYP.TYPE_8 = ''F05'' OR (TYP.TYPE_8 = ''F01'' AND TYP.TYPE_6 = ''B04''))
    INNER JOIN MST_BOND_CREDIT_RATING RT ON RT.O_CODE = PRD.ISSUER AND RT.O_TYPE = ''01''
    WHERE VAL.CDATE = DATE''${valDate}'' - 1 AND VAL.PORTFOLIO_ID IN  ${portfolioCode} AND RT.GRADE_RESULT = ''02'' GROUP BY PRD.ISSUER
  UNION ALL
    SELECT
     SUM(CASE  WHEN N.PS IN(''T01'',''T04'',''T52'',''T25'',''T64'') THEN NVL(N.TRADE_AMT,0)
     WHEN n.PS =''T49'' THEN NVL(-1*n.SHARE_AMT*100,0)
     ELSE  NVL(-1*N.TRADE_AMT,0)
     END) TRADE_AMT, T2.ISSUER RKEY
    FROM TRD_PRODUCT_DEAL_ADD M
    INNER JOIN TRD_PRODUCT_DEAL N ON M.TRADE_ID = N.TRADE_ID
    INNER JOIN FIN_PRODUCT T2 ON T2.FINPROD_ID = N.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE T3 ON N.FINPROD_ID = T3.FINPROD_ID AND T3.BRANCH = 0 AND (T3.TYPE_8 = ''F05'' OR (T3.TYPE_8 = ''F01'' AND T3.TYPE_6 = ''B04''))
    INNER JOIN MST_BOND_CREDIT_RATING RT ON RT.O_CODE = T2.ISSUER AND RT.O_TYPE = ''01''
    WHERE M.PORTFOLIO_ID IN  ${portfolioCode} AND N.TRADE_DATE = DATE''${valDate}'' AND RT.GRADE_RESULT = ''02''
     AND  n.PS IN (''T01'', ''T02'', ''T03'', ''T04'', ''T19'', ''T07'', ''T11'', ''T52'', ''T22'', ''T23'', ''T38'', ''T39'',''T25'',''T49'',''T64'',''T63'')
     AND N.TRADE_STATUS = ''01''
    AND N.IS_CANCEL = ''N''
    GROUP BY T2.ISSUER
  UNION ALL
    SELECT
      SUM(CASE  WHEN N.PS IN(''T01'',''T04'',''T52'',''T25'',''T64'') THEN NVL(N.TRADE_AMT,0)
     WHEN n.PS =''T49'' THEN NVL(-1*n.SHARE_AMT*100,0)
     ELSE  NVL(-1*N.TRADE_AMT,0)
     END) TRADE_AMT, T2.ISSUER RKEY
    FROM TRD_PRODUCT_TEMP_DEAL_ADD M
    INNER JOIN TRD_PRODUCT_TEMP_DEAL N ON M.TRADE_ID = N.TRADE_ID
    INNER JOIN FIN_PRODUCT T2 ON T2.FINPROD_ID = N.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE T3 ON N.FINPROD_ID = T3.FINPROD_ID AND T3.BRANCH = 0 AND (T3.TYPE_8 = ''F05'' OR (T3.TYPE_8 = ''F01'' AND T3.TYPE_6 = ''B04''))
    INNER JOIN MST_BOND_CREDIT_RATING RT ON RT.O_CODE = T2.ISSUER AND RT.O_TYPE = ''01''
    WHERE M.PORTFOLIO_ID IN  ${portfolioCode} AND N.TRADE_DATE = DATE''${valDate}'' AND RT.GRADE_RESULT = ''02''
    AND  n.PS IN (''T01'', ''T02'', ''T03'', ''T04'', ''T19'', ''T07'', ''T11'', ''T52'', ''T22'', ''T23'', ''T38'', ''T39'',''T25'',''T49'',''T64'',''T63'')
    AND N.TRADE_STATUS = ''01''
    AND N.IS_CANCEL = ''N''
    GROUP BY T2.ISSUER
  UNION ALL
    SELECT
      SUM(CASE  WHEN n.PS IN(''T01'',''T04'',''T52'',''T64'') THEN NVL(n.TRADE_AMT,0)
  --债转股流程中
    WHEN n.PS IN(''T49'') THEN NVL(n.SHARE_AMT*100*-1,0)
     ELSE  NVL(-1*n.TRADE_AMT,0)
     END
 ) TRADE_AMT,
     T2.ISSUER RKEY
    FROM WFL_TRD_PRODUCT_DEAL_ADD M
    INNER JOIN WFL_TRD_PRODUCT_DEAL N ON M.TRADE_ID = N.TRADE_ID AND N.TRADE_STATUS != ''03''
  INNER JOIN SYS_WFL_BUSINESS_LIST SWBL ON N.WORKFLOW_ID = SWBL.SEQ_NO AND SWBL.PROCESS_STATE != ''BACK''
    INNER JOIN FIN_PRODUCT T2 ON T2.FINPROD_ID = N.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE T3 ON N.FINPROD_ID = T3.FINPROD_ID AND T3.BRANCH = 0 AND (T3.TYPE_8 = ''F05'' OR (T3.TYPE_8 = ''F01'' AND T3.TYPE_6 = ''B04''))
