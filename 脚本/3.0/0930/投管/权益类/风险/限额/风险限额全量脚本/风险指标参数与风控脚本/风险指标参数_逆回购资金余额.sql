V_CONTENT_01_02_03 CLOB := 'select
   m.PORTFOLIO_ID AS RKEY,NVL(SUM(NVL(m.MARKET_VALUE,0)+nvl(m.TDY_INTINCEXP, 0)),0) as  RVALUE from PTL_SEC_PIERCE_VALUTION m
  INNER JOIN FIN_TRADE_PRODUCT n on m.FINPROD_ID = n.FINPROD_ID and n.FINPROD_TYPE2 in (''F03'',''F05'') 
  where  m.CDATE =date''${valDate}''-1 group by m.PORTFOLIO_ID
 union all
   select t.PTL_BAG_ID as RKEY,
   ( select NVL(SUM(NVL(m.MARKET_VALUE,0)+nvl(m.TDY_INTINCEXP, 0)),0) as  RVALUE from PTL_SEC_PIERCE_VALUTION m
  INNER JOIN FIN_TRADE_PRODUCT n on m.FINPROD_ID = n.FINPROD_ID and n.FINPROD_TYPE2 in (''F03'',''F05'') 
  where    m.CDATE =date''${valDate}''-1  AND
  m.PORTFOLIO_ID in (   select t1.PORTFOLIO_ID from RSK_PORTFOLIO_PACKAGE_DTL t1  inner join PTL_PORTFOLIO t2 on t1.PORTFOLIO_ID=t2.PORTFOLIO_ID and t2.MDATE>date''${valDate}'' where t1.PTL_BAG_ID=t.PTL_BAG_ID)
   )
   from RSK_PORTFOLIO_PACKAGE t';

----事后(日间)
V_CONTENT_04 CLOB := 'select sum(TRADE_AMT) as tradeAmt from
(
  select
  NVL(SUM(NVL(m.MARKET_VALUE,0)+nvl(m.TDY_INTINCEXP, 0)),0) as  TRADE_AMT from PTL_SEC_PIERCE_VALUTION m
  INNER JOIN FIN_TRADE_PRODUCT n on m.FINPROD_ID = n.FINPROD_ID and n.FINPROD_TYPE2 in (''F03'',''F05'') AND n.BRANCH=0
  where m.PORTFOLIO_ID in ${portfolioCode}  and  m.CDATE =date''${valDate}''-1

union ALL
  select
     SUM(CASE  WHEN n.PS IN(''T01'') THEN NVL(n.TRADE_AMT,0)
     ELSE  NVL(-1*n.TRADE_AMT,0)
     END ) TRADE_AMT
  from TRD_PRODUCT_DEAL_ADD m
  inner join TRD_PRODUCT_DEAL n on m.TRADE_ID=n.TRADE_ID
  INNER JOIN FIN_TRADE_PRODUCT t2 on t2.FINPROD_ID=n.FINPROD_ID and t2.FINPROD_TYPE2 in (''F03'',''F05'') AND t2.BRANCH=0
  where m.PORTFOLIO_ID in ${portfolioCode} and n.TRADE_DATE=date''${valDate}'' and n.PS in (''T01'',''T07'',''T95'',''T96'',''T54'',''T55'',''T56'')
   AND n.TRADE_STATUS = ''01''
   AND n.IS_CANCEL = ''N''

union ALL
  select
       SUM(CASE  WHEN n.PS IN(''T01'',''03'') THEN NVL(n.TRADE_AMT,0)
     ELSE  NVL(-1*n.TRADE_AMT,0)
     END ) TRADE_AMT
 from TRD_PRODUCT_TEMP_DEAL_ADD m
  inner join TRD_PRODUCT_TEMP_DEAL n on m.TRADE_ID=n.TRADE_ID
  INNER JOIN FIN_TRADE_PRODUCT t2 on t2.FINPROD_ID=n.FINPROD_ID and t2.FINPROD_TYPE2 in (''F03'',''F05'') AND t2.BRANCH=0
  where m.PORTFOLIO_ID in ${portfolioCode} and n.TRADE_DATE=date''${valDate}'' and  n.PS in (''T01'',''T07'',''T95'',''T96'',''T54'',''T55'',''T56'')
   AND n.TRADE_STATUS = ''01''
   AND n.IS_CANCEL = ''N''

union ALL
  select
     SUM(CASE  WHEN n.PS IN(''T01'',''03'') THEN NVL(n.TRADE_AMT,0)
     ELSE  NVL(-1*n.TRADE_AMT,0)
     END ) TRADE_AMT from WFL_TRD_PRODUCT_DEAL_ADD m
  inner join WFL_TRD_PRODUCT_DEAL n on m.TRADE_ID=n.TRADE_ID and n.TRADE_STATUS != ''03''
  INNER JOIN WFL_PA_TRD_PRODUCT_DEAL t2 on t2.TRADE_ID=n.TRADE_ID and t2.PA_BUSS_TYPE in (''19'',''75'')
  where m.PORTFOLIO_ID in ${portfolioCode} and n.TRADE_DATE=date''${valDate}'' and n.PS in (''T01'')
    AND n.TRADE_STATUS = ''01''
   AND n.IS_CANCEL = ''N''
)';

