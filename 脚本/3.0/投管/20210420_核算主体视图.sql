--核算主体信息
CREATE OR REPLACE VIEW V_ACCT_SUBJECT_INFO AS
SELECT 
  P.PORTFOLIO_ID,                               /*组合代码*/
  P.PORTFOLIO_ID AS ACCT_SUBJECT_ID,            /*核算主体代码*/
  'F18' AS ACCT_SUBJECT_TYPE,                   /*核算主体类型*/
  P.PORTFOLIO_NAME AS ACCT_SUBJECT_NAME,         /*核算主体名称*/
  P.PROFIT_TYPE,                 /*收益类型*/
  P.VDATE AS ACCT_SUBJECT_VDATE					/*核算主体起息日*/
FROM PTL_PORTFOLIO P
WHERE P.PROFIT_TYPE ='02' OR P.PARENT_PORTFOLIO_ID IS NOT NULL
UNION ALL
SELECT FPA.PORTFOLIO_ID,
FP.FINPROD_ID AS ACCT_SUBJECT_ID,
FP.FINPROD_TYPE AS ACCT_SUBJECT_TYPE,
NVL(FP.FINPROD_ABBR,FP.FINPROD_NAME) AS ACCT_SUBJECT_NAME,
FP.PROFIT_TYPE,
FP.VDATE AS ACCT_SUBJECT_VDATE	 
FROM FIN_PRODUCT FP
LEFT JOIN FIN_PRODUCT_ADD FPA ON FP.FINPROD_ID = FPA.FINPROD_ID
WHERE FP.PROFIT_TYPE != '02'
AND FP.P_FINPROD_ID IS NULL
AND FP.FINPROD_TYPE = 'F16';
/

--核算分层：用于筛选前台指定产品的交易
CREATE OR REPLACE VIEW V_ACCT_LAYERING_INFO AS
SELECT 
  FPA.PORTFOLIO_ID, /*组合代码*/
  P.FINPROD_ID,     /*金融产品代码*/
  P.FINPROD_TYPE,    /*金融产品类型*/
  NVL(P.FINPROD_ABBR,P.FINPROD_NAME) AS FINPROD_NAME,
  P.VDATE,
  P.P_FINPROD_ID,
  P.PROFIT_TYPE,
  FPA.IS_CYCLE
FROM FIN_PRODUCT P 
LEFT JOIN FIN_PRODUCT_ADD FPA ON P.FINPROD_ID = FPA.FINPROD_ID
WHERE P.FINPROD_TYPE = 'F16';


