CREATE TABLE
    CREDIT_LINES_PIERCE
    (
        SEQNO VARCHAR2(32) NOT NULL,
        CUSTOMER_ID VARCHAR2(120),
        CDATE DATE,
        PLAN_ASSET_ID VARCHAR2(32),
        CCY VARCHAR2(10),
        CREDIT_AMT NUMBER(30,2),
        INSTITUTION_CODE VARCHAR2(64),
        CREATE_USER VARCHAR2(20) NOT NULL,
        CREATE_DEPT VARCHAR2(32),
        CREATE_TIME TIMESTAMP(6) NOT NULL,
        UPDATE_USER VARCHAR2(20) NOT NULL,
        UPDATE_TIME TIMESTAMP(6) NOT NULL,
        CREDIT_MST_ID VARCHAR2(10),
        CREDIT_FLAG VARCHAR2(50),
        CONSTRAINT PK_CREDIT_LINES_PIERCE PRIMARY KEY (SEQNO)
    );
