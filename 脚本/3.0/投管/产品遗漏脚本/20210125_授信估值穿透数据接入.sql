    '资管计划代码';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.CCY
IS
    '币种';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.CREDIT_AMT
IS
    '占用前剩余额度';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.INSTITUTION_CODE
IS
    '机构代码';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.CREATE_USER
IS
    '创建人';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.CREATE_DEPT
IS
    '创建部门';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.CREATE_TIME
IS
    '创建时间';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.UPDATE_USER
IS
    '更新人';
COMMENT ON COLUMN CREDIT_LINES_PIERCE.UPDATE_TIME
IS
    '更新时间';
