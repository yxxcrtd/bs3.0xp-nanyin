--创建并初始化待更新数据
CREATE TABLE BOK_BUSS_DETSUB_FOUR AS
SELECT A.BOOKSET_ID,
       A.DETAIL_SUBJECT_NO,
       A.DETAIL_SUBJECT_NAME,
       B.SUBJECT_NAME || A.DETAIL_SUBNAME_TAIL AS NEW_DETAIL_SUBJECT_NAME
  FROM BOK_BUSS_DETSUB A
  LEFT JOIN BOK_BOOKSET C
    ON A.BOOKSET_ID = C.BOOKSET_ID
  LEFT JOIN BOK_SUBJECT B
    ON B.BOOKSET_ID = C.BOOKSET_ID_TMPL
   AND A.FSUBJECT_ID = B.SUBJECT_NO
 WHERE B.SUBJECT_NAME IS NOT NULL
 AND A.DETAIL_SUBJECT_NAME != B.SUBJECT_NAME || A.DETAIL_SUBNAME_TAIL;

--业务明细科目表：四级科目名称更新
UPDATE BOK_BUSS_DETSUB A SET 
   A.DETAIL_SUBJECT_NAME = (SELECT C.NEW_DETAIL_SUBJECT_NAME FROM BOK_BUSS_DETSUB_FOUR C WHERE A.BOOKSET_ID = C.BOOKSET_ID AND A.DETAIL_SUBJECT_NO = C.DETAIL_SUBJECT_NO)
   ,A.UPDATE_USER='sjzl',A.UPDATE_TIME=SYSDATE
WHERE EXISTS (
 SELECT 1 FROM BOK_BUSS_DETSUB_FOUR D WHERE A.BOOKSET_ID = D.BOOKSET_ID AND A.DETAIL_SUBJECT_NO = D.DETAIL_SUBJECT_NO
);

--删除中间表
DROP TABLE BOK_BUSS_DETSUB_FOUR;
