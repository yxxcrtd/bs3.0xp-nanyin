
UPDATE FIN_PRODUCT_ADD 
SET TRADE_PLAT = '03'
WHERE FINPROD_ID IN (SELECT fp.FINPROD_ID FROM FIN_PRODUCT fp 
LEFT JOIN FIN_PRODUCT_ADD fpa
ON fpa.FINPROD_ID = fp.FINPROD_ID 
WHERE fp.TRADE_MARKET ='03' AND fpa.IS_NET_SETT = 'N' AND fp.FINPROD_TYPE2 ='F01');

