AND EXISTS (
  SELECT 1 FROM TRD_PRODUCT_DEAL A
  WHERE EXISTS (
    SELECT * FROM FIN_PRODUCT B WHERE A.FINPROD_ID = B.FINPROD_ID
    AND B.FINPROD_TYPE='F17' AND (B.PROFIT_TYPE IS NULL OR B.PROFIT_TYPE='02')
  ) 
  AND S.BUSI_NO = A.TRADE_ID
);

