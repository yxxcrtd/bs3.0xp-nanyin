/**1.科目扩展四级科目数据准备 **/
/**创建临时表：提取待处理数据**/
CREATE TABLE BOK_BOOKDETAIL_CURRENT_KZ AS
SELECT DISTINCT A.BOOKSET_ID,
	B.BUSI_ID,
	A.SUBJECT_NO,
	E.SUBJECT_NAME,
	A.DETAIL_SUBJECT_NO,
	B.BUSI_DETAIL_TYPE,
	B.DETAIL_SUBJECT_NO_TAIL,
	B.DETAIL_SUBNAME_TAIL,
	A.BOK_DETAIL_ID,
	H.TERM_TYPE,
	EXT.PARAM_VALUE,
CASE WHEN H.FINPROD_TYPE IN ('F02','F03','F04','F05','F08','F09')
		THEN H.TERM_TYPE
	WHEN H.FINPROD_TYPE='F21'
		THEN DECODE(EXT.PARAM_VALUE,'02',H.TERM_TYPE,H.FINPROD_ID)
ELSE H.FINPROD_ID END FINPROD_ID,
CASE WHEN H.FINPROD_TYPE IN ('F02','F03','F04','F05')
		THEN DECODE(H.TERM_TYPE,'R007','7天','R014','14天','R9M','9个月','R6M','6个月','R001','1天','R4M','4个月','R021','21天','R1Y','1年','R2M','2个月','R3M','3个月','R0','未知','R1M','1个月')
	WHEN H.FINPROD_TYPE IN ('F08','F09') OR (H.FINPROD_TYPE='F21' AND EXT.PARAM_VALUE='02')
		THEN DECODE(H.TERM_TYPE,'IB0001','隔夜','IB01M','1个月','IB12M','12个月','IB02M','2个月','IB0021','21天','IB03M','3个月','IB1Y','1年以上','IB0014','14天','IB09M','9个月','IB0007','7天','IB06M','6个月')
ELSE H.FINPROD_NAME END FINPROD_NAME
FROM BOK_BOOKDETAIL_CURRENT A
LEFT JOIN BOK_DETAIL_ID B
	ON A.BOOKSET_ID = B.BOOKSET_ID
	AND A.BOK_DETAIL_ID = B.BOK_DETAIL_ID
LEFT JOIN BOK_BOOKSET C
	ON A.BOOKSET_ID = C.BOOKSET_ID
LEFT JOIN BOK_BOOKSET_EXT EXT
	ON C.BOOKSET_ID = EXT.BOOKSET_ID
	AND EXT.PARAM_CODE = 'TYJK_FORSUBJECT'
LEFT JOIN BOK_SUBJECT E
	ON C.BOOKSET_ID_TMPL = E.BOOKSET_ID
	AND E.SUBJECT_NO = A.SUBJECT_NO
LEFT JOIN (SELECT D.FINPROD_ID,
		D.FINPROD_TYPE,
		NVL(D.FINPROD_ABBR, D.FINPROD_NAME) FINPROD_NAME,
		E.TERM_TYPE
		FROM FIN_PRODUCT D
		LEFT JOIN FIN_PRODUCT_ADD E
		ON D.FINPROD_ID = E.FINPROD_ID
	UNION ALL
		SELECT G.FINPROD_ID,
		G.FINPROD_TYPE,
		G.FINPROD_ID AS FINPROD_NAME,
		G.TERM_TYPE
		FROM FIN_TRADE_PRODUCT G
		LEFT JOIN FIN_PRODUCT_TYPE F
		ON G.FINPROD_ID = F.FINPROD_ID
		AND G.BRANCH = F.BRANCH
		WHERE G.BRANCH = 0
		AND G.FINPROD_TYPE != 'F21'
	UNION ALL
		SELECT I.ACCT_NO, 'F20' FINPROD_TYPE, I.ACCT_NAME, NULL
		FROM STL_CAPACCT_INFO I) H
		ON B.BUSI_ID = H.FINPROD_ID
		WHERE A.DETAIL_SUBJECT_NO IS NULL
 		AND (A.SUBJECT_NO IN ('10020101','10020113','10210101','10210103','10310101','10310104','22410301','12210401'));
/**2.开始业务数据更新**/
/**2.1业务明细科目表数据**/
INSERT INTO BOK_BUSS_DETSUB( 
BOOKSET_ID,DETAIL_SUBJECT_NO,DETAIL_SUBJECT_NAME,
FSUBJECT_ID,CREATE_USER,CREATE_DEPT,CREATE_TIME, 
UPDATE_USER,UPDATE_TIME,DETAIL_SUBJECT_NO_TAIL,DETAIL_SUBNAME_TAIL 
) 
SELECT 
	A.BOOKSET_ID, 
	A.SUBJECT_NO||NVL(A.DETAIL_SUBJECT_NO,A.FINPROD_ID) AS DETAIL_SUBJECT_NO, 
	A.SUBJECT_NAME||NVL(A.DETAIL_SUBNAME_TAIL,FINPROD_NAME) AS DETAIL_SUBJECT_NAME, 
	A.SUBJECT_NO AS FSUBJECT_ID,
	'sjzl', 
	null, 
	SYSDATE, 
	'sjzl', 
	SYSDATE, 
	NVL(A.DETAIL_SUBJECT_NO,A.FINPROD_ID), 
	NVL(A.DETAIL_SUBNAME_TAIL,FINPROD_NAME)
FROM BOK_BOOKDETAIL_CURRENT_KZ A 
	WHERE  NOT EXISTS( 
	SELECT 1 FROM BOK_BUSS_DETSUB B WHERE A.BOOKSET_ID = B.BOOKSET_ID
	AND A.SUBJECT_NO||NVL(A.DETAIL_SUBJECT_NO,A.FINPROD_ID) = B.DETAIL_SUBJECT_NO
	);
	COMMIT;
/**2.2 账务明细代码表、账务明细历史表、账务明细当前表数据**/
DECLARE
	CURSOR LIST IS
		SELECT 
		BOOKSET_ID,BUSI_ID,SUBJECT_NO,SUBJECT_NAME,DETAIL_SUBJECT_NO,
		BUSI_DETAIL_TYPE,DETAIL_SUBJECT_NO_TAIL,DETAIL_SUBNAME_TAIL,BOK_DETAIL_ID,
		TERM_TYPE,PARAM_VALUE,FINPROD_ID,FINPROD_NAME 
		FROM BOK_BOOKDETAIL_CURRENT_KZ; 
	BEGIN
	FOR item IN LIST
LOOP
/**账务明细代码表**/  
UPDATE BOK_DETAIL_ID  SET   
	DETAIL_SUBJECT_NO_TAIL = NVL(DETAIL_SUBJECT_NO_TAIL,item.FINPROD_ID), 
	DETAIL_SUBNAME_TAIL = NVL(DETAIL_SUBNAME_TAIL,item.FINPROD_NAME), 
	UPDATE_USER ='sjzl', 
	UPDATE_TIME = SYSDATE
	WHERE BOK_DETAIL_ID = item.BOK_DETAIL_ID 
	AND BOOKSET_ID = item.BOOKSET_ID 
	AND (DETAIL_SUBJECT_NO_TAIL IS NULL OR DETAIL_SUBNAME_TAIL IS NULL);
/**账务明细历史表**/
UPDATE BOK_BOOKDETAIL_ALL SET
	DETAIL_SUBJECT_NO = SUBJECT_NO|| NVL(item.DETAIL_SUBJECT_NO_TAIL,item.FINPROD_ID),                                                                                     
	UPDATE_USER ='sjzl', 
	UPDATE_TIME = SYSDATE
	WHERE BOOKSET_ID = item.BOOKSET_ID 
	AND BOK_DETAIL_ID = item.BOK_DETAIL_ID
	AND SUBJECT_NO = item.SUBJECT_NO;
/**账务明细当前表**/ 
UPDATE BOK_BOOKDETAIL_CURRENT SET  
	DETAIL_SUBJECT_NO = SUBJECT_NO|| NVL(item.DETAIL_SUBJECT_NO_TAIL,item.FINPROD_ID),                                                                                     
	UPDATE_USER ='sjzl', 
	UPDATE_TIME = SYSDATE 
	WHERE BOOKSET_ID = item.BOOKSET_ID 
	AND BOK_DETAIL_ID = item.BOK_DETAIL_ID
	AND SUBJECT_NO = item.SUBJECT_NO;  
COMMIT;
END LOOP;
END;
/
/**3.结束-业务数据更新，数据验证通过后，删除过程使用的临时表**/
DROP TABLE BOK_BOOKDETAIL_CURRENT_KZ;