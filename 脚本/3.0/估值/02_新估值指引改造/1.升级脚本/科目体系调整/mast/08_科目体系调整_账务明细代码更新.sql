--创建并初始化待更新数据
CREATE TABLE BOK_DETAIL_ID_CL AS
SELECT 
   A.BOOKSET_ID,
   B.BUSI_ID,
   B.BUSI_DETAIL_TYPE,
   B.BOK_DETAIL_ID,
   C.ACCT_NAME
FROM BOK_BOOKSET_CAPACCT_INFO A
LEFT JOIN BOK_DETAIL_ID B ON A.BOOKSET_ID = B.BOOKSET_ID AND A.ACCT_NO = B.BUSI_ID AND A.ACCT_TYPE = B.BUSI_DETAIL_TYPE
     AND A.CCY = B.CCY
LEFT JOIN STL_CAPACCT_INFO C ON A.ACCT_NO = C.ACCT_NO  AND A.CCY = C.CCY;

--账务明细代码表：四级科目尾号、四级科目尾号名称初始化
UPDATE BOK_DETAIL_ID B 
 SET B.DETAIL_SUBJECT_NO_TAIL = B.BUSI_ID,
     B.DETAIL_SUBNAME_TAIL = (SELECT F.ACCT_NAME FROM BOK_DETAIL_ID_CL F WHERE B.BOOKSET_ID = F.BOOKSET_ID AND B.BOK_DETAIL_ID = F.BOK_DETAIL_ID)
WHERE EXISTS (
 SELECT 1 FROM BOK_DETAIL_ID_CL E WHERE B.BOOKSET_ID = E.BOOKSET_ID AND B.BOK_DETAIL_ID = E.BOK_DETAIL_ID
);

--删除中间表
DROP TABLE BOK_DETAIL_ID_CL;
