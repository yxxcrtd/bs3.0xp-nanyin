DROP TABLE CHB_CPROD_BALANCE;

CREATE TABLE
    CHB_CPROD_BALANCE
    (
        BAL_ID CHAR(36) NOT NULL,
        PROD_ID VARCHAR2(50),
        P_PROD_ID VARCHAR2(50),
        PERIOD_ID VARCHAR2(50),
        VALUE_DATE DATE,
        MDATE DATE,
        BALANCE NUMBER(30,2),
        CCY VARCHAR2(50),
        CREATE_USER VARCHAR2(20) NOT NULL,
        CREATE_TIME TIMESTAMP(6) NOT NULL,
        UPDATE_USER VARCHAR2(20) NOT NULL,
        UPDATE_TIME TIMESTAMP(6) NOT NULL,
        CONSTRAINT CHB_CPROD_BALANCE_PK PRIMARY KEY (BAL_ID)
    );
