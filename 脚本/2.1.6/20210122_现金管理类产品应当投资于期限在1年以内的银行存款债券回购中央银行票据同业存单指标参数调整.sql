--修改指标参数 买入-卖出-实时sql
declare
	sql01 clob:= 'WITH ASSET AS (
    -- 逆回购交易
    SELECT FINPROD_ID,MDATE,NULL FROM FIN_TRADE_PRODUCT
    WHERE FINPROD_TYPE2 IN (''F03'',''F05'')
  UNION ALL
    -- 活期存款
    SELECT FP.FINPROD_ID,DATE''${valDate}'' MDATE,FP.FINPROD_NAME FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FP.FINPROD_TYPE2 = ''F07'' AND FPT.TYPE_6 = ''D03''
  UNION ALL
    -- 非活期存款
    SELECT FP.FINPROD_ID,FP.MDATE,FP.FINPROD_NAME FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FP.FINPROD_TYPE2 = ''F07'' AND FPT.TYPE_6 != ''D03''
  UNION ALL
    -- 央票、同业存单（非含权）
    SELECT FP.FINPROD_ID,NVL(FXZ.MDATE,FP.MDATE) MDATE,FP.FINPROD_NAME FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    LEFT JOIN (
        SELECT FCP.FINPROD_ID,FCP.MDATE FROM FIN_CASH_PLAN FCP
        WHERE FCP.FINPROD_TYPE2 = ''F01'' AND FCP.CASH_TYPE = ''04'' AND FCP.CASH_ID IN (
            SELECT FCI.CASH_ID FROM FIN_CASH_INFO FCI
            INNER JOIN FIN_CASH_CALC_RULE FCC ON FCC.CASH_ID = FCI.CASH_ID AND FCC.CALC_TYPE = ''02''
            WHERE FCI.CASH_TYPE_1 = ''02''
        )
    ) FXZ ON FXZ.FINPROD_ID = FP.FINPROD_ID
    WHERE FP.FINPROD_TYPE2 = ''F01'' AND FPT.type_6 IN (''B03'',''B04'') AND FP.IS_RIGHT = ''N''
  UNION ALL
    -- 央票、同业存单（含权）
    SELECT FP.FINPROD_ID,
    CASE WHEN NVL(FXZ.MDATE, t1.MDATE) < t1.MDATE THEN NVL(FXZ.MDATE,FP.MDATE) ELSE NVL(t1.MDATE,FP.MDATE) END MDATE,FP.FINPROD_NAME
    FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    AND FP.FINPROD_TYPE2 = ''F01'' AND FPT.type_6 IN (''B03'',''B04'')
    LEFT JOIN (
        SELECT FCP.FINPROD_ID,FCP.MDATE FROM FIN_CASH_PLAN FCP
        WHERE FCP.FINPROD_TYPE2 = ''F01'' AND FCP.CASH_TYPE = ''04'' AND FCP.CASH_ID IN (
            SELECT FCI.CASH_ID FROM FIN_CASH_INFO FCI
            INNER JOIN FIN_CASH_CALC_RULE FCC ON FCC.CASH_ID = FCI.CASH_ID AND FCC.CALC_TYPE = ''02''
            WHERE FCI.CASH_TYPE_1 = ''02''
        )
    ) FXZ ON FXZ.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN (
        SELECT FINPROD_ID,min(EXERCISE_DATE) MDATE FROM FIN_EXERCISE_PLAN
        WHERE EXERCISE_DATE >= DATE ''${valDate}''
        GROUP BY FINPROD_ID
    ) t1 ON t1.FINPROD_ID = FP.FINPROD_ID
    WHERE FP.IS_RIGHT = ''Y''
)
SELECT TO_NUMBER(ASSET.MDATE - DATE ''${valDate}'' - 1) RVALUE, ASSET.FINPROD_ID RKEY
FROM ASSET WHERE ASSET.MDATE > DATE ''${valDate}'' AND ASSET.FINPROD_ID IN ${assetCode}
UNION ALL
SELECT 0 RVALUE,${assetCode} RKEY FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM ASSET WHERE ASSET.FINPROD_ID IN ${assetCode})
 ';
begin
	update rsk_isup_indicator_para_dtl set content = sql01 where para_code = 'XJGLLCPYDTZYQJXZNYNDYXHCKZXQ' and para_granularity  in ('01','02','03');
end;
