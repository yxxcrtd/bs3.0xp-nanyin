declare
		num number; 
begin
       select count(1) into num from user_tables where table_name = 'SYS_WFL_MODULE_INSTITUTION';
       if num>0 then
           execute immediate 'drop table SYS_WFL_MODULE_INSTITUTION';
       end if;
end;
/
CREATE TABLE
    SYS_WFL_MODULE_INSTITUTION
    (
        MODULE_ID VARCHAR2(64) NOT NULL,
		INSTITUTION_CODE VARCHAR2(50) DEFAULT 'ALL' NOT NULL,
        CREATE_USER VARCHAR2(20) NOT NULL,
        CREATE_DEPT VARCHAR2(32),
        CREATE_TIME TIMESTAMP(6) NOT NULL,
        UPDATE_USER VARCHAR2(20) NOT NULL,
        UPDATE_TIME TIMESTAMP(6) NOT NULL,
        CONSTRAINT PK_SYS_WFL_MODULE_INSTITUTION PRIMARY KEY (MODULE_ID,INSTITUTION_CODE)
    );
COMMENT ON TABLE SYS_WFL_MODULE_INSTITUTION
IS
    '模板机构关联表';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.MODULE_ID
IS
    '模板代码';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.INSTITUTION_CODE
IS
    '机构代码';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.CREATE_USER
IS
    '创建人';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.CREATE_DEPT
IS
    '创建部门';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.CREATE_TIME
IS
    '创建时间';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.UPDATE_USER
IS
    '更新人';
COMMENT ON COLUMN SYS_WFL_MODULE_INSTITUTION.UPDATE_TIME
IS
    '更新时间';
