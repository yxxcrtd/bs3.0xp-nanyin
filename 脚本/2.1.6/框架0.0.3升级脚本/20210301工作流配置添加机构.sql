insert into SYS_WFL_MODULE_INSTITUTION(MODULE_ID,INSTITUTION_CODE,CREATE_USER,CREATE_DEPT,CREATE_TIME,UPDATE_USER,UPDATE_TIME)
select  ID_,'ALL','admin',null,sysdate,'admin',sysdate from ACT_RE_MODEL;

