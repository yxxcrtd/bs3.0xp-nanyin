DROP TABLE BUSI_TYPE_MAPPING;
CREATE TABLE
    BUSI_TYPE_MAPPING
    (
        SEQNO VARCHAR2(32) NOT NULL,
        FINPROD_TYPE_TG VARCHAR2(50),
        PS VARCHAR2(50),       
        BUSI_TYPE VARCHAR2(50),
        BUSI_TYPE_NAME VARCHAR2(200),
        CONSTRAINT PK_BUSI_TYPE_MAPPING PRIMARY KEY (SEQNO)
    );
COMMENT ON TABLE BUSI_TYPE_MAPPING
IS
    '投管业务类型映射关系表';
COMMENT ON COLUMN BUSI_TYPE_MAPPING.SEQNO
IS
    '流水号';
COMMENT ON COLUMN BUSI_TYPE_MAPPING.FINPROD_TYPE_TG
IS
    '金融产品类型(投管用)【FINPROD_TYPE_TG】';
COMMENT ON COLUMN BUSI_TYPE_MAPPING.PS
IS
    '交易方向【PS】';
COMMENT ON COLUMN BUSI_TYPE_MAPPING.BUSI_TYPE
IS
    '业务类型';
COMMENT ON COLUMN BUSI_TYPE_MAPPING.BUSI_TYPE_NAME
IS
    '业务类型名称';