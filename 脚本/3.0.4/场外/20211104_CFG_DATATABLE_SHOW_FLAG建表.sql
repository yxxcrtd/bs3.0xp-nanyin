DROP TABLE CFG_DATATABLE_SHOW_FLAG;
CREATE TABLE
    CFG_DATATABLE_SHOW_FLAG
    (
        PAGECODE VARCHAR2(36) NOT NULL,
        DTCODE VARCHAR2(36) NOT NULL,
		SPCDCODE VARCHAR2(36) DEFAULT '999999' NOT NULL,
        PAGENAME VARCHAR2(60),
        DTNAME VARCHAR2(60) DEFAULT '1' ,
        EFFERANGE NUMBER DEFAULT 0,
        RANGEID VARCHAR2(36) NOT NULL,
        UPDATETIME VARCHAR2(19) NOT NULL,
        CONSTRAINT PK_CFG_DATATABLE_SHOW_FLAG PRIMARY KEY (PAGECODE, DTCODE, SPCDCODE,RANGEID)
    );
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.PAGECODE
IS
    '页面编码';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.DTCODE
IS
    '页面区域编码';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.SPCDCODE
IS
    '特殊条件编码';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.PAGENAME
IS
    '页面名称';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.DTNAME
IS
    '数据表格名称';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.EFFERANGE
IS
    '有效范围(0:全局,1:个人)';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.RANGEID
IS
    '范围ID(见有效范围字段)';
COMMENT ON COLUMN CFG_DATATABLE_SHOW_FLAG.UPDATETIME
IS
    '更新时间';
