
DROP TABLE ETR_ENTRUST_RE;
CREATE TABLE "ETR_ENTRUST_RE" 
   (	"ENTRUST_ID" VARCHAR2(32) NOT NULL ENABLE, 
	"TOTAL_ENTRUST_ID" VARCHAR2(32), 
	"CREATE_USER" VARCHAR2(20) NOT NULL ENABLE, 
	"CREATE_DEPT" VARCHAR2(32), 
	"CREATE_TIME" DATE NOT NULL ENABLE, 
	"UPDATE_USER" VARCHAR2(20) NOT NULL ENABLE, 
	"UPDATE_TIME" DATE NOT NULL ENABLE
   ) ;

COMMENT ON COLUMN "ETR_ENTRUST_RE"."ENTRUST_ID" IS '指令编号';
 
   COMMENT ON COLUMN "ETR_ENTRUST_RE"."TOTAL_ENTRUST_ID" IS '汇总指令编号';
 
   COMMENT ON COLUMN "ETR_ENTRUST_RE"."CREATE_USER" IS '创建人';
 
   COMMENT ON COLUMN "ETR_ENTRUST_RE"."CREATE_DEPT" IS '创建部门';
 
   COMMENT ON COLUMN "ETR_ENTRUST_RE"."CREATE_TIME" IS '创建时间';
 
   COMMENT ON COLUMN "ETR_ENTRUST_RE"."UPDATE_USER" IS '更新人';
 
   COMMENT ON COLUMN "ETR_ENTRUST_RE"."UPDATE_TIME" IS '更新时间';
 
   COMMENT ON TABLE "ETR_ENTRUST_RE"  IS '指令关系表';