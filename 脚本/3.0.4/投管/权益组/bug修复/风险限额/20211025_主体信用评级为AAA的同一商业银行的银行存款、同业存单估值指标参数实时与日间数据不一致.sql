  INNER JOIN  RT ON RT.O_CODE = T2.ISSUER
    WHERE N.COUNTER_ID IN  ${portfolioCode} AND N.TRADE_DATE = DATE''${valDate}'' AND RT.GRADE_RESULT = ''02'' AND N.PS = ''T02''
