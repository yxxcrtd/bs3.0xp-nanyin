V_CONTENT_04 CLOB := 'WITH RT AS (SELECT O_CODE,max(GRADE_RESULT) GRADE_RESULT FROM (
         SELECT O_CODE,GRADE_RESULT,rank() over (partition by O_CODE order by GRADE_DATE desc) rk
         FROM MST_BOND_CREDIT_RATING where O_TYPE = ''01'') where rk =1 group by O_CODE)
SELECT SUM(NVL(TRADE_AMT,0)) AS RVALUE, RKEY FROM (
    SELECT
        SUM(NVL(VAL.MARKET_VALUE ,0)+nvl(VAL.TDY_INTINCEXP, 0)) TRADE_AMT, PRD.ISSUER RKEY
    FROM PTL_SEC_PIERCE_VALUTION VAL
    INNER JOIN FIN_PRODUCT PRD ON VAL.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE TYP ON TYP.FINPROD_ID = VAL.FINPROD_ID AND (TYP.TYPE_8 = ''F05'' OR (TYP.TYPE_8 = ''F01'' AND TYP.TYPE_6 = ''B04''))
