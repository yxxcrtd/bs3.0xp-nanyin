-- 增加菜单分割线
DROP TABLE SYS_MENU_SPLIT;
CREATE TABLE SYS_MENU_SPLIT(
	MENU_ID VARCHAR(50) NOT NULL,
	SPLIT_ORDER_NO NUMBER(10) NOT NULL,
	SPLIT_MEMO VARCHAR(200),
	CREATE_USER VARCHAR(20) NOT NULL,
	CREATE_DEPT VARCHAR(32),
	CREATE_TIME TIMESTAMP(6) NOT NULL,
	UPDATE_USER VARCHAR(20) NOT NULL,
	UPDATE_TIME TIMESTAMP(6) NOT NULL,
	CONSTRAINT PK_SYS_MENU_SPLIT PRIMARY KEY (MENU_ID, SPLIT_ORDER_NO)
);
COMMENT ON TABLE SYS_MENU_SPLIT IS '菜单分割线';
COMMENT ON COLUMN SYS_MENU_SPLIT.MENU_ID IS '菜单代码';
COMMENT ON COLUMN SYS_MENU_SPLIT.SPLIT_ORDER_NO IS '分割线排列顺序';
COMMENT ON COLUMN SYS_MENU_SPLIT.SPLIT_MEMO IS '分割线说明';
COMMENT ON COLUMN SYS_MENU_SPLIT.CREATE_USER IS '创建人';
COMMENT ON COLUMN SYS_MENU_SPLIT.CREATE_DEPT IS '创建部门';
COMMENT ON COLUMN SYS_MENU_SPLIT.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN SYS_MENU_SPLIT.UPDATE_USER IS '更新人';
COMMENT ON COLUMN SYS_MENU_SPLIT.UPDATE_TIME IS '更新时间';