--估值表导入信息记录表
DROP TABLE VALTBL_IMPORT_HIS_TRACE;
CREATE TABLE VALTBL_IMPORT_HIS_TRACE
(
	FILE_NAME VARCHAR2(200) NOT NULL,
	FILE_PATH VARCHAR2(200) NOT NULL,
	PORTFOLIO_ID VARCHAR2(50),
	PORTFOLIO_NAME VARCHAR2(50)NOT NULL,
	VALDATE DATE NOT NULL,
	IMPDATE DATE NOT NULL,
	IMPORT_TYPE VARCHAR2(50),
	ERROR_CODE VARCHAR2(50),
	START_TIME TIMESTAMP(6),
	END_TIME TIMESTAMP(6),
	CREATE_USER VARCHAR2(20) NOT NULL,
	CREATE_DEPT VARCHAR2(32),
	CREATE_TIME TIMESTAMP(6) NOT NULL,
	UPDATE_USER VARCHAR2(20) NOT NULL,
	UPDATE_TIME TIMESTAMP(6) NOT NULL
);
COMMENT ON TABLE VALTBL_IMPORT_HIS_TRACE IS '估值表导入历史信息记录表';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.FILE_NAME IS '文件名';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.FILE_PATH IS '文件路径';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.PORTFOLIO_ID IS '委外组合代码';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.PORTFOLIO_NAME IS '委外组合名称';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.VALDATE IS '估值日期';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.IMPDATE IS '导入日期';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.IMPORT_TYPE IS '处理状态：R处理中、T正常结束、F异常结束';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.ERROR_CODE IS '异常代码';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.START_TIME IS '开始时间';
COMMENT ON COLUMN VALTBL_IMPORT_HIS_TRACE.END_TIME IS '结束时间';
