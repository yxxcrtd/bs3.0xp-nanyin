--估值表导入信息记录表
DROP TABLE RSK_OUT_VALTBL_IMPORT_HIS;
CREATE TABLE RSK_OUT_VALTBL_IMPORT_HIS
(
	FILE_NAME VARCHAR2(200) NOT NULL,
	FILE_PATH VARCHAR2(200) NOT NULL,
	PORTFOLIO_ID VARCHAR2(50),
	PORTFOLIO_NAME VARCHAR2(200)NOT NULL,
	VALDATE DATE NOT NULL,
	IMPDATE DATE NOT NULL,
	IMPORT_TYPE VARCHAR2(50),
	ERROR_CODE VARCHAR2(50),
	START_TIME TIMESTAMP(6),
	END_TIME TIMESTAMP(6),
	CREATE_USER VARCHAR2(20) NOT NULL,
	CREATE_DEPT VARCHAR2(32),
	CREATE_TIME TIMESTAMP(6) NOT NULL,
	UPDATE_USER VARCHAR2(20) NOT NULL,
	UPDATE_TIME TIMESTAMP(6) NOT NULL,
	CONSTRAINT RSK_OUT_VALTBL_IMPORT_HIS PRIMARY KEY (FILE_NAME, PORTFOLIO_NAME, VALDATE)
);
COMMENT ON TABLE RSK_OUT_VALTBL_IMPORT_HIS
IS
    '估值表导入信息记录表';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.FILE_NAME
IS
    '文件名';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.FILE_PATH
IS
    '文件路径';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.PORTFOLIO_ID
IS
    '委外组合代码';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.PORTFOLIO_NAME
IS
    '委外组合名称';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.VALDATE
IS
    '估值日期';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.IMPDATE
IS
    '导入日期';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.IMPORT_TYPE
IS
    '处理状态：R处理中、T正常结束、F异常结束';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.ERROR_CODE
IS
    '异常代码';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.START_TIME
IS
    '开始时间';
COMMENT ON COLUMN RSK_OUT_VALTBL_IMPORT_HIS.END_TIME
IS
    '结束时间';
