                          where a.p_prod_id = info.prod_id
                            and a.status = 'C') > 0 then
                        'C'
                    else
                        info.status
                   end )
           else info.status
           end as STATUS,
       ISSUE_STATUS_REMARK,
       RAISE_MIN,
       RAISE_MAX,
       RAISE_CCY,
       VDATE,
       FIRST_OPEN_DAY,
       ACT_MDATE,
