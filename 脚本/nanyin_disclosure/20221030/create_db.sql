       PROD_INVEST_TYPE,
       REVEAL_CHANNEL,
       DEAL_CAL,
       FINA_TYPE,
       TRU_ACCOUNT,
       TRU_FEE_RAGE,
       TRU_ACCOUNT_NUM,
       TRU_ACCOUNT_NAME,
       PROD_TERM_TYPE,
       BASIS,
       TARGET_SALE,
       IS_LAYER,
       PRO_MANAGER,
       PRO_CUSTODIAN,
       HUGE_REDEEM_THRESHOLD,
       SALE_AMT_STR,
       OPERATE_MODE,
       F_PROD_ID,
       PRODPROFITFLAG,
       SALETARGET_DECLARE,
       BONUS_MODE,
       LOWEST_AMT
