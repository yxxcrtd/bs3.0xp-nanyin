       HOLDDAY,
       TRUSTPART,
       ISSUE_STATUS,
       REP_PROD_TYPE,
       ERRORMSG,
       CREATE_USER,
       CREATE_DEPT,
       CREATE_TIME,
       UPDATE_USER,
       UPDATE_TIME,
       case REP_PROD_TYPE
           when '01' then
