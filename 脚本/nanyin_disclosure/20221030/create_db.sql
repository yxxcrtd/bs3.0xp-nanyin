DROP TABLE DIS_TRU_BANK CASCADE CONSTRAINTS;
CREATE TABLE DIS_TRU_BANK (
    TRU_UUID   VARCHAR2(60) NOT NULL,
    TRU_NAME         VARCHAR2(60) NOT NULL,
    TRU_SIMPLE_NAME  VARCHAR2(50),
    DATA_STATUS     VARCHAR2(10),
    CREATE_USER     VARCHAR2(20),
    CREATE_TIME     TIMESTAMP,
    UPDATE_USER     VARCHAR2(20),
