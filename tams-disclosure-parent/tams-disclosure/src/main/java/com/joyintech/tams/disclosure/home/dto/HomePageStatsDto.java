package com.joyintech.tams.disclosure.home.dto;

public class HomePageStatsDto {

	private int counts;
	private String homePageType;
	private String revealStatus;
	private String confirmStatus;
	private String reviewStatus;
	private String reviewTgStatus;
	public int getCounts() {
		return counts;
	}
	public void setCounts(int counts) {
		this.counts = counts;
	}
	public String getHomePageType() {
		return homePageType;
	}
	public void setHomePageType(String homePageType) {
		this.homePageType = homePageType;
	}
	public String getRevealStatus() {
		return revealStatus;
	}
	public void setRevealStatus(String revealStatus) {
		this.revealStatus = revealStatus;
	}
	public String getConfirmStatus() {
		return confirmStatus;
	}
	public void setConfirmStatus(String confirmStatus) {
		this.confirmStatus = confirmStatus;
	}
	public String getReviewStatus() {
		return reviewStatus;
	}
	public void setReviewStatus(String reviewStatus) {
		this.reviewStatus = reviewStatus;
	}
	public String getReviewTgStatus() {
		return reviewTgStatus;
	}
	public void setReviewTgStatus(String reviewTgStatus) {
		this.reviewTgStatus = reviewTgStatus;
	}
	
	
}
