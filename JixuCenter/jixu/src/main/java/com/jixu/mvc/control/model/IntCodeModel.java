package com.jixu.mvc.control.model;

public class IntCodeModel {
	
	//当年的总天数
	private int totalDays;
	
	//当年的计算天数
	private int calDays;
	

	public int getTotalDays() {
		return totalDays;
	}

	public void setTotalDays(int totalDays) {
		this.totalDays = totalDays;
	}

	public int getCalDays() {
		return calDays;
	}

	public void setCalDays(int calDays) {
		this.calDays = calDays;
	}
	
}
