--适配器自定义序列,用于文件生成的末尾序列号

CREATE TABLE "ADPT_EXPFILE_SEQ" 
(	
  	"SOURCEID" NUMBER(10,0) NOT NULL ENABLE, 
	"LATESTNUM" NUMBER(14,0) NOT NULL ENABLE,
  	"STARTNUM" NUMBER(10,0),
  	"MAXNUM" NUMBER(14,0),
	"ROLLTYPE" VARCHAR2(3) NOT NULL ENABLE,
	"CREATE_TIME" TIMESTAMP (6), 
	"CREATE_DEPT" VARCHAR2(50), 
	"UPDATE_TIME" TIMESTAMP (6), 
	"UPDATE_USER" VARCHAR2(20), 
	"CREATE_USER" VARCHAR2(20),
	PRIMARY KEY ("SOURCEID")
);

COMMENT ON TABLE "ADPT_EXPFILE_SEQ"  IS '适配器导出文件自定义序列';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."SOURCEID" IS '适配器编号';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."LATESTNUM" IS '最新的值';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."STARTNUM" IS '开始值';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."MAXNUM" IS '最大值';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."ROLLTYPE" IS '规则类型';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."CREATE_DEPT" IS '更新部门';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."CREATE_USER" IS '创建用户';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."UPDATE_TIME" IS '更新时间';
COMMENT ON COLUMN "ADPT_EXPFILE_SEQ"."UPDATE_USER" IS '更新用户';